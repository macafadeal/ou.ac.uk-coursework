function add(a, b) {
    return a + b;
}

console.log(add(1, 1));

function sub(a, b) {
    return a - b;
}

function mult(a, b) {
    return a * b;
}

function div(a, b) {
    return a / b;
}

console.log(sub(4, 3), sub(8, 12), sub(8, 0));
console.log(mult(4, 3), mult(4, 1), mult(4, 0));
console.log(div(4, 3), div(4, 1), div(4, 0));
